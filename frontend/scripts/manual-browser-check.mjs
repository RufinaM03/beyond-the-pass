import assert from 'node:assert/strict';
import {mkdir, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {chromium} from 'playwright-core';

const base = process.env.BTP_BASE_URL || 'http://127.0.0.1:8011';
assert.ok(/^http:\/\/127\.0\.0\.1:\d+$/.test(base) || (process.env.BTP_REMOTE_ACCEPTANCE === '1' && base === 'https://d1qxms20novn1p.cloudfront.net'));
const output = resolve(import.meta.dirname, '../../artifacts/manual-browser', process.env.BTP_VERIFY_TARGET || 'local');
await mkdir(output, {recursive: true});
const browser = await chromium.launch({executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true});
const page = await browser.newPage({viewport: {width: 1440, height: 1080}});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const posts = [];
page.on('request', request => {if (request.method() === 'POST') posts.push(new URL(request.url()).pathname);});
const checks = [];
try {
  const before = await (await page.request.get(base + '/api/evaluation')).json();
  const queueBefore = await (await page.request.get(base + '/api/queue?capacity=10')).json();
  await page.goto(base, {waitUntil: 'networkidle'});
  await page.getByRole('link', {name: /Try a prediction/}).click();
  await page.getByRole('heading', {name: 'Try a prediction', exact: true}).waitFor();
  await page.getByRole('button', {name: 'Load illustrative inputs'}).click();
  const calculate = page.getByRole('button', {name: 'Calculate exploratory score'});
  assert.equal(await calculate.isDisabled(), true);
  assert.equal(posts.length, 0);
  await page.getByRole('checkbox').check();
  await page.getByLabel('Inspection date (optional context)').fill('2023-05-31');
  await calculate.click();
  await page.getByRole('heading', {name: 'Exploratory prioritization score', exact: true}).waitFor();
  await page.getByText(/Nominal window: 2024-02-29 to 2024-08-31/).waitFor();
  await page.getByText(/This scenario receives no historical rank or percentile/).waitFor();
  await page.getByText(/Miles: the DVSA guide/).waitFor();
  checks.push('Illustrative inputs, mandatory eligibility, explicit miles, actual trusted score and calendar window');
  await page.getByText('Technical explanation: all model contributions', {exact: true}).click();
  await page.getByRole('table').getByText('Intercept', {exact: true}).waitFor();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path: resolve(output, 'prediction.png'), fullPage: true});
  checks.push('Plain-language signed associations and collapsible full technical terms');
  await page.getByRole('spinbutton', {name: /^Recorded mileage \(miles\)/}).fill('');
  await calculate.click();
  await page.getByText(/frozen median/).waitFor();
  await page.getByText('Unknown (submitted blank)', {exact: true}).waitFor();
  checks.push('Blank mileage remains null and is explicitly imputed using frozen median');
  await page.getByRole('spinbutton', {name: /^Vehicle age in years/}).fill('');
  await calculate.click();
  await page.getByRole('heading', {name: 'Insufficient data — no score'}).waitFor();
  checks.push('Both optional predictors missing: no fabricated zero score');
  await page.getByRole('spinbutton', {name: /^Vehicle age in years/}).fill('999');
  await calculate.click();
  await page.getByText('Extrapolation warning', {exact: true}).waitFor();
  checks.push('Outside-training-range scenario has an explicit extrapolation warning');
  await page.getByLabel('Current brake advisory count', {exact: true}).fill('3');
  const postCount = posts.length;
  await calculate.click();
  await page.getByRole('alert').getByText('Total advisories must include all brake advisories.', {exact: true}).waitFor();
  assert.equal(posts.length, postCount);
  checks.push('Inconsistent counts blocked before network submission');
  await page.getByLabel('Current brake advisory count', {exact: true}).fill('1');
  await page.setViewportSize({width: 390, height: 844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path: resolve(output, 'mobile-form.png'), fullPage: true});
  await page.reload({waitUntil: 'networkidle'});
  await page.getByRole('heading', {name: 'Try a prediction', exact: true}).waitFor();
  assert.equal(await page.getByRole('spinbutton', {name: /^Vehicle age in years/}).inputValue(), '');
  assert.equal(await page.getByRole('checkbox').isChecked(), false);
  checks.push('Responsive390px, SPA refresh and no persisted form submission');
  assert.deepEqual(await (await page.request.get(base + '/api/evaluation')).json(), before);
  assert.deepEqual(await (await page.request.get(base + '/api/queue?capacity=10')).json(), queueBefore);
  assert.ok(posts.every(path => path === '/api/predict/manual'));
  assert.deepEqual(errors, []);
  checks.push('Historical queue and complete saved evaluation unchanged; only bounded manual POST used');
  await writeFile(resolve(output, 'checks.json'), JSON.stringify({base, checked_at: new Date().toISOString(), illustrative_inputs: true, checks, page_errors: errors, prediction_posts: posts.length}, null, 2));
  console.log(`Manual browser verification passed: ${checks.length} checks; ${output}`);
} finally {
  await browser.close();
}
